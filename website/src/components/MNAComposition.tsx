/**
 * MNAComposition — poster-scale procedural compositions.
 *
 * Companion to MNAGlyph. Where glyphs are dense small marks (100×100 viewBox,
 * geometric construction visible), compositions are atmospheric large pieces
 * (poster-sized, single dominant gesture, heavy negative space, optional
 * caption). Modeled directly on the four "Visual Language" pieces in the MNA
 * brand board: fragmentation / absence / structure / interruption.
 *
 * Use cases: hero placeholders, work-without-render fallbacks, exhibition
 * group covers, OG share cards, founding-document heads, 404 art.
 */

import * as React from "react";
import { hashSeed } from "./MNAGlyph";
import manifestData from "@/lib/composition-manifest.json";

/* The manifest JSON is generated by `npm run generate-compositions`. We
 * import it from src/lib/ rather than public/ so Next.js handles it as a
 * normal compile-time module rather than a runtime asset fetch. Wrapped in
 * a defensive accessor so a malformed file can't crash the page. */
function getThemeAssets(theme: string): string[] {
  try {
    const themes = (manifestData as { themes?: Record<string, string[]> }).themes;
    if (!themes || typeof themes !== "object") return [];
    const arr = themes[theme];
    return Array.isArray(arr) ? arr : [];
  } catch {
    return [];
  }
}

/* ─── RNG ───────────────────────────────────────────────────────────────── */

function mulberry32(seed: number) {
  let a = seed >>> 0;
  return function () {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/* ─── Theme registry ────────────────────────────────────────────────────── */

export type CompositionTheme =
  | "fragmentation"
  | "absence"
  | "structure"
  | "interruption";

export type Aspect = "portrait" | "square" | "landscape";

export interface CompositionMeta {
  key: CompositionTheme;
  label: string;
  caption: string;       // brand-board sub-line ("Signal breaks through structure.")
  description: string;
  defaultAspect: Aspect;
  /** "light" = cream paper bg, dark marks. "dark" = ink bg, light marks. */
  defaultTone: "light" | "dark";
}

export const COMPOSITIONS: Record<CompositionTheme, CompositionMeta> = {
  fragmentation: {
    key: "fragmentation",
    label: "Fragmentation",
    caption: "Signal breaks through structure.",
    description: "Dense horizontal bands obscuring an implied vertical presence.",
    defaultAspect: "portrait",
    defaultTone: "light",
  },
  absence: {
    key: "absence",
    label: "Absence",
    caption: "Meaning holds as much power as presence.",
    description: "Spare, ceremonial — a dominant mark and an answering void.",
    defaultAspect: "square",
    defaultTone: "light",
  },
  structure: {
    key: "structure",
    label: "Structure",
    caption: "Systems create order. Art disrupts it.",
    description: "Constructivist grid with a sparse rhythm of filled cells.",
    defaultAspect: "square",
    defaultTone: "light",
  },
  interruption: {
    key: "interruption",
    label: "Interruption",
    caption: "Breaks introduce new possibilities.",
    description: "A single vertical light-zip piercing a dark field.",
    defaultAspect: "portrait",
    defaultTone: "dark",
  },
};

export const ALL_COMPOSITIONS = Object.keys(COMPOSITIONS) as CompositionTheme[];

const ASPECT_VIEWBOX: Record<Aspect, { w: number; h: number }> = {
  portrait: { w: 600, h: 900 },
  square: { w: 800, h: 800 },
  landscape: { w: 1200, h: 750 },
};

/* ─── Public component ─────────────────────────────────────────────────── */

export interface MNACompositionProps {
  theme: CompositionTheme;
  seed: string | number;
  aspect?: Aspect;
  tone?: "light" | "dark";
  /** Show the brand-board caption ("FRAGMENTATION / Signal breaks…") */
  showCaption?: boolean;
  className?: string;
  /** ARIA title; if absent, the SVG is decorative. */
  title?: string;
}

export default function MNAComposition({
  theme,
  seed,
  aspect,
  tone,
  showCaption = false,
  className,
  title,
}: MNACompositionProps) {
  const meta = COMPOSITIONS[theme];
  const a = aspect ?? meta.defaultAspect;
  const t = tone ?? meta.defaultTone;
  const { w, h } = ASPECT_VIEWBOX[a];
  const n = typeof seed === "number" ? seed >>> 0 : hashSeed(String(seed));
  const palette = t === "dark" ? DARK : LIGHT;

  /* Prefer a raster asset from the manifest if one exists for this theme.
     Falls back to procedural SVG if the manifest is empty (e.g. before the
     generation script has been run, or for a newly-added theme). */
  const themeAssets = getThemeAssets(theme);
  if (themeAssets.length > 0) {
    const src = themeAssets[n % themeAssets.length];
    return (
      <div
        className={className}
        style={{ position: "relative", aspectRatio: `${w} / ${h}` }}
      >
        {/* eslint-disable-next-line @next/next/no-img-element */}
        <img
          src={src}
          alt={title ?? meta.label}
          aria-hidden={title ? undefined : true}
          style={{
            position: "absolute",
            inset: 0,
            width: "100%",
            height: "100%",
            objectFit: "cover",
            display: "block",
          }}
        />
        {showCaption ? <CaptionOverlay meta={meta} palette={palette} /> : null}
      </div>
    );
  }

  /* Procedural SVG fallback. */
  const body = RENDERERS[theme](n, w, h, palette);
  return (
    <svg
      viewBox={`0 0 ${w} ${h}`}
      className={className}
      preserveAspectRatio="xMidYMid slice"
      aria-hidden={title ? undefined : true}
      role={title ? "img" : undefined}
    >
      {title ? <title>{title}</title> : null}
      <rect width={w} height={h} fill={palette.bg} />
      {body}
      {showCaption ? <Caption meta={meta} w={w} h={h} palette={palette} /> : null}
    </svg>
  );
}

/* HTML overlay caption used on top of raster assets. */
function CaptionOverlay({ meta, palette }: { meta: CompositionMeta; palette: Palette }) {
  return (
    <div
      style={{
        position: "absolute",
        left: "5%",
        bottom: "5%",
        color: palette.caption,
        textShadow:
          palette === DARK
            ? "0 1px 2px rgba(0,0,0,0.55)"
            : "0 1px 1px rgba(255,255,255,0.4)",
        pointerEvents: "none",
      }}
    >
      <div
        style={{
          fontSize: 11,
          letterSpacing: "0.22em",
          fontWeight: 600,
          textTransform: "uppercase",
          opacity: 0.9,
        }}
      >
        {meta.label}
      </div>
      <div
        style={{
          marginTop: 4,
          fontSize: 12,
          opacity: 0.7,
          fontStyle: "italic",
        }}
      >
        {meta.caption}
      </div>
    </div>
  );
}

/* Per-tone palette. */
const LIGHT = {
  bg: "#EAE7E2",        // warm paper
  ink: "#0A0A0A",        // ink
  inkSoft: "#2A2A2A",
  inkFaint: "#8A8A8A",
  caption: "#0A0A0A",
};
const DARK = {
  bg: "#0A0A0A",
  ink: "#F4F2EE",
  inkSoft: "#C0BDB8",
  inkFaint: "#5A5854",
  caption: "#F4F2EE",
};
type Palette = typeof LIGHT;

/* Caption: "01.  FRAGMENTATION  / Signal breaks through structure." */
function Caption({
  meta,
  w,
  h,
  palette,
}: {
  meta: CompositionMeta;
  w: number;
  h: number;
  palette: Palette;
}) {
  const padX = w * 0.05;
  const padY = h * 0.06;
  return (
    <g>
      <text
        x={padX}
        y={h - padY - 22}
        fill={palette.caption}
        fontFamily="ui-sans-serif, system-ui, sans-serif"
        fontSize="14"
        fontWeight="500"
        letterSpacing="3"
        opacity="0.85"
      >
        {meta.label.toUpperCase()}
      </text>
      <text
        x={padX}
        y={h - padY}
        fill={palette.caption}
        fontFamily="ui-sans-serif, system-ui, sans-serif"
        fontSize="13"
        opacity="0.55"
      >
        {meta.caption}
      </text>
    </g>
  );
}

