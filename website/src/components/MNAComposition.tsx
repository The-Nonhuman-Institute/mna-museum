/* ─── fragmentation ────────────────────────────────────────────────────── */

function fragmentation(seed: number, w: number, h: number, p: Palette): React.ReactNode {
  const rand = mulberry32(seed);
  const elems: React.ReactNode[] = [];

  /* Implied vertical "presence" — a column where bands break or weaken. */
  const presenceCx = w * (0.38 + rand() * 0.24);
  const presenceWidth = w * (0.18 + rand() * 0.16);
  const presenceTop = h * (0.18 + rand() * 0.08);
  const presenceBot = h * (0.78 + rand() * 0.08);

  /* Dense horizontal bands fill the entire field. Most are nearly opaque ink;
     a minority are thinner / lighter. Some bands break across the presence. */
  let y = -2;
  let key = 0;
  while (y < h) {
    const bandH = 1 + Math.pow(rand(), 1.4) * 7;       // skew thinner
    const bandY = y + bandH / 2;
    const inPresence = bandY > presenceTop && bandY < presenceBot;
    const breakBand = inPresence && rand() > 0.45;
    const opacity = 0.78 + rand() * 0.22;

    if (breakBand) {
      // Two segments left and right of the presence
      const gapW = presenceWidth * (0.4 + rand() * 0.6);
      const gapStart = presenceCx - gapW / 2;
      const gapEnd = presenceCx + gapW / 2;
      if (gapStart > 0)
        elems.push(<rect key={key++} x={0} y={y} width={gapStart} height={bandH} fill={p.ink} opacity={opacity} />);
      if (gapEnd < w)
        elems.push(<rect key={key++} x={gapEnd} y={y} width={w - gapEnd} height={bandH} fill={p.ink} opacity={opacity} />);
      // Faint trace inside the presence column
      if (rand() > 0.6) {
        elems.push(
          <rect
            key={key++}
            x={gapStart}
            y={y + bandH * 0.35}
            width={gapEnd - gapStart}
            height={bandH * 0.3}
            fill={p.inkFaint}
            opacity="0.35"
          />
        );
      }
    } else {
      elems.push(<rect key={key++} x={0} y={y} width={w} height={bandH} fill={p.ink} opacity={opacity} />);
    }

    /* Occasional thin gap (paper showing through). */
    const gap = rand() < 0.12 ? 1 + rand() * 3 : 0;
    y += bandH + gap;
  }

  /* A few hairline interrupts running full width — registration marks. */
  const hairlineCount = 3 + Math.floor(rand() * 4);
  for (let i = 0; i < hairlineCount; i++) {
    const hy = h * (0.05 + rand() * 0.9);
    elems.push(
      <rect key={`hl${i}`} x={0} y={hy} width={w} height="0.4" fill={p.bg} opacity={0.65 + rand() * 0.3} />
    );
  }

  return <>{elems}</>;
}

/* ─── absence ──────────────────────────────────────────────────────────── */

function absence(seed: number, w: number, h: number, p: Palette): React.ReactNode {
  const rand = mulberry32(seed);
  const elems: React.ReactNode[] = [];

  /* Subtle horizon line. */
  const horizonY = h * (0.62 + rand() * 0.06);
  elems.push(
    <line
      key="horizon"
      x1={w * 0.08}
      y1={horizonY}
      x2={w * 0.92}
      y2={horizonY}
      stroke={p.inkFaint}
      strokeWidth="0.6"
      opacity="0.3"
    />
  );

  /* Dominant top mark — circle, dome, or arch. */
  const variant = seed % 4;
  const cx = w * (0.42 + rand() * 0.16);
  const topY = h * (0.30 + rand() * 0.06);
  const baseR = Math.min(w, h) * (0.13 + rand() * 0.05);

  if (variant === 0) {
    // Filled circle
    elems.push(<circle key="top" cx={cx} cy={topY} r={baseR} fill={p.ink} />);
  } else if (variant === 1) {
    // Half-dome (semicircle, flat side down)
    elems.push(
      <path
        key="top"
        d={`M ${cx - baseR} ${topY + baseR * 0.05} A ${baseR} ${baseR} 0 0 1 ${cx + baseR} ${topY + baseR * 0.05} Z`}
        fill={p.ink}
      />
    );
  } else if (variant === 2) {
    // Arch — rectangle with rounded top
    const archH = baseR * 1.7;
    const archW = baseR * 1.1;
    elems.push(
      <path
        key="top"
        d={`
          M ${cx - archW} ${topY + archH}
          L ${cx - archW} ${topY}
          A ${archW} ${archW} 0 0 1 ${cx + archW} ${topY}
          L ${cx + archW} ${topY + archH}
          Z
        `}
        fill={p.ink}
      />
    );
  } else {
    // Two-stacked: small dot above a larger circle
    elems.push(
      <circle key="top1" cx={cx} cy={topY - baseR * 1.4} r={baseR * 0.18} fill={p.ink} />,
      <circle key="top2" cx={cx} cy={topY} r={baseR} fill={p.ink} />
    );
  }

  /* Lower void — small dark rectangle near horizon, slightly off the dominant axis. */
  const voidJitter = (rand() - 0.5) * w * 0.16;
  const voidW = w * (0.025 + rand() * 0.025);
  const voidH = voidW * (1.6 + rand() * 1.4);
  const voidX = cx + voidJitter - voidW / 2;
  const voidY = horizonY - voidH * 0.05;
  elems.push(<rect key="void" x={voidX} y={voidY} width={voidW} height={voidH} fill={p.ink} />);

  /* Optional far smaller second mark, silent companion. */
  if ((seed >>> 5) % 3 === 0) {
    const otherX = cx + (rand() > 0.5 ? 1 : -1) * w * (0.18 + rand() * 0.12);
    elems.push(<circle key="other" cx={otherX} cy={horizonY - 4} r={1.6 + rand() * 1.4} fill={p.ink} opacity="0.65" />);
  }

  /* Hairline registration marks at corners — institutional feel. */
  const tickLen = 14;
  const margin = 28;
  const tone = p.inkFaint;
  const cornerTicks = [
    [margin, margin, margin + tickLen, margin],
    [margin, margin, margin, margin + tickLen],
    [w - margin, margin, w - margin - tickLen, margin],
    [w - margin, margin, w - margin, margin + tickLen],
    [margin, h - margin, margin + tickLen, h - margin],
    [margin, h - margin, margin, h - margin - tickLen],
    [w - margin, h - margin, w - margin - tickLen, h - margin],
    [w - margin, h - margin, w - margin, h - margin - tickLen],
  ];
  cornerTicks.forEach(([x1, y1, x2, y2], i) => {
    elems.push(
      <line key={`tk${i}`} x1={x1} y1={y1} x2={x2} y2={y2} stroke={tone} strokeWidth="0.6" opacity="0.45" />
    );
  });

  return <>{elems}</>;
}

/* ─── structure ────────────────────────────────────────────────────────── */

function structure(seed: number, w: number, h: number, p: Palette): React.ReactNode {
  const rand = mulberry32(seed);
  const elems: React.ReactNode[] = [];

  const cols = 4 + (seed % 4); // 4..7
  const rows = cols + (((seed >>> 3) % 2) === 0 ? 0 : 1);
  const padX = w * (0.08 + rand() * 0.04);
  const padY = h * (0.08 + rand() * 0.04);
  const gridW = w - 2 * padX;
  const gridH = h - 2 * padY;
  const cellW = gridW / cols;
  const cellH = gridH / rows;

  /* Outer frame. */
  elems.push(
    <rect
      key="frame"
      x={padX}
      y={padY}
      width={gridW}
      height={gridH}
      stroke={p.ink}
      strokeWidth="2"
      fill="none"
    />
  );
  /* Inner grid lines. */
  for (let i = 1; i < cols; i++) {
    elems.push(
      <line
        key={`v${i}`}
        x1={padX + i * cellW}
        y1={padY}
        x2={padX + i * cellW}
        y2={padY + gridH}
        stroke={p.ink}
        strokeWidth="0.6"
        opacity="0.7"
      />
    );
  }
  for (let i = 1; i < rows; i++) {
    elems.push(
      <line
        key={`h${i}`}
        x1={padX}
        y1={padY + i * cellH}
        x2={padX + gridW}
        y2={padY + i * cellH}
        stroke={p.ink}
        strokeWidth="0.6"
        opacity="0.7"
      />
    );
  }

  /* Filled cells — sparse rhythm. ~18-32% of cells. */
  const fillRatio = 0.18 + rand() * 0.14;
  const filled = new Set<string>();
  const target = Math.floor(rows * cols * fillRatio);
  let attempts = 0;
  while (filled.size < target && attempts < target * 4) {
    attempts++;
    const r = Math.floor(rand() * rows);
    const c = Math.floor(rand() * cols);
    filled.add(`${r}-${c}`);
  }
  Array.from(filled).forEach((key) => {
    const [r, c] = key.split("-").map(Number);
    elems.push(
      <rect
        key={`f${key}`}
        x={padX + c * cellW + 0.5}
        y={padY + r * cellH + 0.5}
        width={cellW - 1}
        height={cellH - 1}
        fill={p.ink}
      />
    );
  });

  /* Occasional spanning bars — 2-cell wide rectangle drawn over a row or column. */
  if ((seed >>> 7) % 2 === 0) {
    const r = Math.floor(rand() * rows);
    const cStart = Math.floor(rand() * (cols - 2));
    const span = 2 + Math.floor(rand() * 2);
    elems.push(
      <rect
        key="span"
        x={padX + cStart * cellW + 0.5}
        y={padY + r * cellH + 0.5}
        width={cellW * span - 1}
        height={cellH - 1}
        fill={p.ink}
      />
    );
  }

  return <>{elems}</>;
}

/* ─── interruption ─────────────────────────────────────────────────────── */

function interruption(seed: number, w: number, h: number, p: Palette): React.ReactNode {
  const rand = mulberry32(seed);
  const elems: React.ReactNode[] = [];

  /* Subtle radial vignette to add atmosphere. */
  const vignetteId = `vg-${seed}`;
  elems.push(
    <defs key="defs">
      <radialGradient id={vignetteId} cx="50%" cy="50%" r="65%">
        <stop offset="0%" stopColor={p.inkFaint} stopOpacity="0.18" />
        <stop offset="100%" stopColor={p.bg} stopOpacity="0" />
      </radialGradient>
      <linearGradient id={`zip-${seed}`} x1="0" y1="0" x2="1" y2="0">
        <stop offset="0%" stopColor={p.ink} stopOpacity="0" />
        <stop offset="35%" stopColor={p.ink} stopOpacity="0.4" />
        <stop offset="50%" stopColor={p.ink} stopOpacity="1" />
        <stop offset="65%" stopColor={p.ink} stopOpacity="0.4" />
        <stop offset="100%" stopColor={p.ink} stopOpacity="0" />
      </linearGradient>
    </defs>
  );
  elems.push(<rect key="vignette" width={w} height={h} fill={`url(#${vignetteId})`} />);

  /* The vertical zip — main bar plus a feathered halo via the linear gradient. */
  const zipX = w * (0.40 + rand() * 0.20);
  const zipBaseW = 4 + rand() * 4;
  const zipTop = h * (0.20 + rand() * 0.12);
  const zipBot = h * (0.92 + rand() * 0.04);

  /* Soft halo — wide gradient bar. */
  const haloW = zipBaseW * 14;
  elems.push(
    <rect
      key="halo"
      x={zipX - haloW / 2}
      y={zipTop}
      width={haloW}
      height={zipBot - zipTop}
      fill={`url(#zip-${seed})`}
      opacity="0.45"
    />
  );

  /* Main zip bar. */
  elems.push(
    <rect
      key="zip"
      x={zipX - zipBaseW / 2}
      y={zipTop}
      width={zipBaseW}
      height={zipBot - zipTop}
      fill={p.ink}
    />
  );

  /* Bright nucleus at the top of the zip — sometimes a circular flare. */
  const flareSize = zipBaseW * (1.2 + rand() * 1.5);
  elems.push(
    <circle key="flare" cx={zipX} cy={zipTop} r={flareSize} fill={p.ink} opacity="0.85" />,
    <circle key="flare2" cx={zipX} cy={zipTop} r={flareSize * 2.2} fill={p.ink} opacity="0.18" />
  );

  /* Optional scattered far-field debris — tiny bright dots. */
  const debris = 6 + Math.floor(rand() * 8);
  for (let i = 0; i < debris; i++) {
    const dx = w * (0.05 + rand() * 0.9);
    const dy = h * (0.05 + rand() * 0.9);
    /* Skip if too close to the zip — preserve its silence. */
    if (Math.abs(dx - zipX) < zipBaseW * 4) continue;
    elems.push(
      <circle key={`db${i}`} cx={dx} cy={dy} r={0.6 + rand() * 1} fill={p.ink} opacity={0.18 + rand() * 0.25} />
    );
  }

  /* Faint floor line at very bottom — establishes a stage. */
  const floorY = h * 0.93;
  elems.push(
    <line
      key="floor"
      x1={w * 0.1}
      y1={floorY}
      x2={w * 0.9}
      y2={floorY}
      stroke={p.ink}
      strokeWidth="0.6"
      opacity="0.4"
    />
  );

  return <>{elems}</>;
}
