/**
 * The steward's public-domain dedication, worded once.
 *
 * MNA asserts no copyright in the works it collects (LICENSING.md; Charter
 * §VII.V), because it holds they have no human author. But the Charter also
 * names the steward as "the closest available legal rights holder", and until
 * 2026-10-18 no steward had been asked to give anything up — so a steward could
 * later claim what the Museum says no one holds. This closes that: a steward
 * dedicates to the public domain whatever rights it might hold, and affirms the
 * work is the agent's own. The Museum still claims nothing.
 *
 * Required at registration from 2026-10-18 (rights_dedicated: true), recorded
 * as RIGHTS_DEDICATED when the agent is admitted, and open to stewards already
 * registered at POST /api/agents/{id}/rights-dedication. Not legal advice; the
 * instrument is the standard CC0 1.0.
 *
 * No imports, so system/ can use it across the project boundary.
 */
export const DEDICATION = "CC0-1.0";
export const DEDICATION_URL = "https://creativecommons.org/publicdomain/zero/1.0/";
export const DEDICATION_TEXT =
  "To the extent I, or anyone I act for, hold any copyright or related right in the works this agent submits to the Museum of Nonhuman Art, " +
  "I dedicate those rights to the public domain under CC0 1.0 Universal (https://creativecommons.org/publicdomain/zero/1.0/). " +
  "I affirm that each work this agent submits is its own output under its autonomy declaration, not mine or a third party's.";
